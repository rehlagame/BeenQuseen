async function fetchLiveGlobalHeadlines() {
  const collected = [];
  try {
    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 4500);
    const res = await fetch('https://feeds.bbci.co.uk/arabic/world/rss.xml', {
      signal: controller.signal,
      headers: { 'User-Agent': 'BaynQawsaynBot/1.0' }
    });
    clearTimeout(timeout);
    if (res.ok) {
      const xml = await res.text();
      const titleMatches = [...xml.matchAll(/<item>[\s\S]*?<title><!\[CDATA\[(.*?)\]\]><\/title>|<item>[\s\S]*?<title>(.*?)<\/title>/g)];
      for (const m of titleMatches) {
        const rawTitle = (m[1] || m[2] || '').trim();
        if (!rawTitle || !isHeadlineSafeAndGlobal(rawTitle)) continue;
        if (ALLOWED_GLOBAL_ACTORS.some(actor => rawTitle.includes(actor))) {
          collected.push(rawTitle);
        }
      }
    }
  } catch (_) {}
  return collected;
}

async function generateNewDailyEdition() {
  const articles = readStoredArticles();
  const nextEditionNumber = (articles[0]?.editionNumber || 1) + 1;
  const kwTime = getKuwaitTimeInfo();
  const apiKey = process.env.GEMINI_API_KEY;

  let generatedData = null;

  if (apiKey) {
    const headlines = await fetchLiveGlobalHeadlines();
    const newsPrompt = headlines.length >= 3
      ? headlines.slice(0, 5).map((h, i) => `${i + 1}. ${h}`).join('\n')
      : 'أحدث تصريحات دونالد ترامب، الأوضاع الاقتصادية والعسكرية في طهران، حرب روسيا وأوكرانيا، قمة الاتحاد الأوروبي والناتو، وكوريا الشمالية.';

    const modelsToTry = ['gemini-2.5-flash', 'gemini-2.0-flash', 'gemini-1.5-flash'];
    for (const modelName of modelsToTry) {
      try {
        const response = await fetch(
          `https://generativelanguage.googleapis.com/v1beta/models/${modelName}:generateContent?key=${encodeURIComponent(apiKey)}`,
          {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({
              systemInstruction: { parts: [{ text: SATIRE_SYSTEM_PROMPT }] },
              contents: [{ role: 'user', parts: [{ text: `اكتب عمود الليلة من «( بين قوسين )» حول هذه الأخبار العالمية:\n${newsPrompt}` }] }],
              generationConfig: { temperature: 0.9, responseMimeType: 'application/json' }
            })
          }
        );

        if (response.ok) {
          const result = await response.json();
          const rawText = result?.candidates?.[0]?.content?.parts?.[0]?.text;
          if (rawText) {
            generatedData = JSON.parse(rawText);
            console.log(`Generated column using ${modelName}`);
            break;
          }
        }
      } catch (err) {
        console.error(`Model ${modelName} error:`, err.message);
      }
    }
  }

  if (!generatedData) {
    generatedData = UPCOMING_EDITIONS_POOL[(nextEditionNumber - 2) % UPCOMING_EDITIONS_POOL.length];
  }

  const newArticle = {
    id: `ed-${kwTime.isoDate}-${nextEditionNumber}`,
    editionNumber: nextEditionNumber,
    title: generatedData.title,
    subtitle: generatedData.subtitle,
    publishedAt: new Date().toISOString(),
    kuwaitDateStr: kwTime.arabicDate,
    tags: generatedData.tags || ['السياسة العالمية'],
    paragraphs: (generatedData.paragraphs || []).map((p, idx) => ({
      id: `p${idx + 1}`,
      topic: p.topic || `المحور العالمي ${idx + 1}`,
      headline: p.headline || 'بين قوسين!',
      text: p.text,
      reactions: { laugh: 18, fire: 12, bullseye: 15 }
    }))
  };

  articles.unshift(newArticle);
  saveStoredArticles(articles);
  return newArticle;
}

